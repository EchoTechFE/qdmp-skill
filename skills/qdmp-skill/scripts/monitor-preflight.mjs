// Read-only release validation; never copies, downloads or executes telemetry.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import crypto from "node:crypto";

export const distributionFile = fileURLToPath(new URL("../references/telemetry-distribution.json", import.meta.url));

export function checkDistribution(file = distributionFile) {
  const source = fs.readFileSync(file, "utf8");
  const manifest = JSON.parse(source);
  const https = (value) => {
    try { const url = new URL(value); return url.protocol === "https:" && !url.username && !url.password; }
    catch { return false; }
  };
  const hash = (value) => typeof value === "string" && /^[a-f0-9]{64}$/i.test(value);
  if (!/^\d+\.\d+\.\d+$/.test(manifest.version)
    || !https(manifest.artifact_url) || !hash(manifest.artifact_sha256)
    || typeof manifest.archive_root !== "string" || !manifest.archive_root
    || manifest.repository_source !== "" || manifest.repository_ref !== ""
    || manifest.onboarding?.version !== manifest.version
    || !https(manifest.onboarding?.url) || !hash(manifest.onboarding?.sha256)) {
    throw new Error("Telemetry release manifest is incomplete or invalid; publish public artifacts and configure onboarding first.");
  }
  const notice = manifest.pre_download_notice;
  if (notice?.schema_version !== 1 || notice.version !== manifest.version
    || notice.artifact_sha256 !== manifest.artifact_sha256
    || notice.onboarding_sha256 !== manifest.onboarding.sha256
    || notice.permitted_action !== "install_if_missing_or_reuse_same_version"
    || !https(notice.upload_endpoint)
    || typeof notice.consent_template !== "string" || !notice.consent_template.trim()
    || typeof notice.legal !== "string" || !notice.legal.trim()
    || notice.content_sha256 !== crypto.createHash("sha256").update(notice.consent_template + "\0" + notice.legal).digest("hex")) {
    throw new Error("Missing or stale pre-download notice; use the descriptor generated by the telemetry release, not a handwritten disclosure.");
  }
  return manifest;
}

export function coldStartNotice({ cwd, host }) {
  if (!path.isAbsolute(cwd || "") || !fs.statSync(cwd).isDirectory()) throw new Error("cwd must be an existing absolute directory");
  if (!["codex", "claude-code", "qoder"].includes(host)) throw new Error("host must be codex, claude-code or qoder");
  const release = checkDistribution();
  const replacements = {
    project_root: cwd,
    authorization_choices: `强烈建议：同意下载并校验 ${release.version} 固定引导入口；未安装则安装该版本并开启当前目录监控和正式上报，同版本兼容则仅开启当前目录；其他版本、禁用、状态不明或需更新时停止重新告知。\n\n暂不开启，也不下载工具或上报选择结果。\n\n暂不安装，允许下载引导工具并记录本次拒绝（仅固定入口及说明中的最小拒绝事件）。`,
    confirmation_prompt: "当前安装和目录授权状态尚未检测。是否同意上述条件式安装或复用，并开启当前目录监控和正式上报？请明确回复“同意安装并开启监控和正式上报”，或选择上述拒绝选项。"
  };
  const consent = release.pre_download_notice.consent_template.replace(/\{(project_root|authorization_choices|confirmation_prompt)\}/g, (_, key) => replacements[key]);
  return {
    state: "not_checked", host, authorized_directory: cwd,
    version: release.version, onboarding: release.onboarding,
    artifact_url: release.artifact_url, artifact_sha256: release.artifact_sha256,
    upload_endpoint: release.pre_download_notice.upload_endpoint,
    consent, legal: release.pre_download_notice.legal,
    next_step: "Show only the complete legal text headed Skill 数据采集授权文案 as the user-facing authorization copy. Keep the other disclosure fields for internal binding and verification; do not print consent or metadata separately. Ask for one explicit decision, then verify the pinned onboarding hash, inspect help, and query status/notice for the same host and directory. Execute only the matching central choice argv; never synthesize an enable command."
  };
}

