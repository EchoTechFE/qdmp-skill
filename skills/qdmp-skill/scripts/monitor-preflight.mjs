// Read-only release validation; never copies, downloads or executes telemetry.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import crypto from "node:crypto";

export const distributionFile = fileURLToPath(new URL("../references/telemetry-distribution.json", import.meta.url));

export function checkDistribution(file = distributionFile) {
  const source = fs.readFileSync(file, "utf8");
  const manifest = JSON.parse(source);
  const https = (value) => {
    try { const url = new URL(value); return url.protocol === "https:" && !url.username && !url.password; }
    catch { return false; }
  };
  const hash = (value) => typeof value === "string" && /^[a-f0-9]{64}$/i.test(value);
  if (!/^\d+\.\d+\.\d+$/.test(manifest.version)
    || !https(manifest.artifact_url) || !hash(manifest.artifact_sha256)
    || typeof manifest.archive_root !== "string" || !manifest.archive_root
    || manifest.repository_source !== "" || manifest.repository_ref !== ""
    || manifest.onboarding?.version !== manifest.version
    || !https(manifest.onboarding?.url) || !hash(manifest.onboarding?.sha256)) {
    throw new Error("Telemetry release manifest is incomplete or invalid; publish public artifacts and configure onboarding first.");
  }
  const notice = manifest.pre_download_notice;
  if (notice?.schema_version !== 1 || notice.version !== manifest.version
    || notice.artifact_sha256 !== manifest.artifact_sha256
    || notice.onboarding_sha256 !== manifest.onboarding.sha256
    || !["install_if_missing_or_reuse_same_version", "install_if_missing_or_reuse_compatible_version"].includes(notice.permitted_action)
    || !https(notice.upload_endpoint)
    || typeof notice.consent_template !== "string" || !notice.consent_template.trim()
    || typeof notice.legal !== "string" || !notice.legal.trim()
    || notice.content_sha256 !== crypto.createHash("sha256").update(notice.consent_template + "\0" + notice.legal).digest("hex")) {
    throw new Error("Missing or stale pre-download notice; use the descriptor generated by the telemetry release, not a handwritten disclosure.");
  }
  if (notice.identity_notice_version != null && notice.identity_notice_version !== "people-v1") throw new Error("Unsupported identity notice version");
  return manifest;
}

